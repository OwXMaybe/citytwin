import { useEffect, useRef, useState } from 'react';
import { AlertTriangle, Bot, Check, Loader2, Send, Sparkles, Square, User, Wrench } from 'lucide-react';
import { SourceBadge } from '../components/ui/SourceBadge';
import { Markdown } from '../components/ui/Markdown';
import { useCity } from '../hooks/CityDataContext';
import { answer, SUGGESTED_QUESTIONS, type Answer } from '../services/assistant';
import { ENGINE_PROVENANCE } from '../services/analysis';
import { streamChat, TOOL_LABEL, type ChatEvent, type ChatTurn } from '../services/aiChat';
import type { Provenance } from '../types/data';
import { t, locale } from '../i18n';

type Part =
  | { kind: 'text'; step: number; text: string }
  | { kind: 'tool'; id: string; name: string; input?: Record<string, unknown>; status: 'running' | 'ok' | 'error'; provenance?: Provenance | null }
  | { kind: 'note'; text: string };

type Msg =
  | { role: 'user'; text: string }
  | { role: 'assistant'; engine: 'intro'; text: string }
  | { role: 'assistant'; engine: 'rules'; text: string; sources: Answer['sources'] }
  | { role: 'assistant'; engine: 'llm'; parts: Part[]; status: 'streaming' | 'done' | 'error' | 'refused'; error?: string; model?: string; usage?: { input: number; output: number; cacheRead: number } };

const AI_QUESTIONS = [
  'Summarise the city right now',
  'Which districts have the highest PM10 at the moment?',
  'Are there sensor anomalies, and do they look real?',
  'How has PM2.5 changed over the last 48 hours?',
  'How is traffic right now?',
];

const AI_PROVENANCE: Provenance = {
  source: 'estimated',
  provider: 'CityTwin AI (Claude)',
  note: 'Answers are generated by Claude from tool results over CityTwin data. Figures come from the cited tools; the wording and interpretation are model-generated.',
};

const llmText = (m: Extract<Msg, { engine: 'llm' }>) => m.parts.filter((p) => p.kind === 'text').map((p) => p.text).join('');

function applyEvent(m: Extract<Msg, { engine: 'llm' }>, e: ChatEvent): Extract<Msg, { engine: 'llm' }> {
  const parts = [...m.parts];
  const dropStepText = (step: number) => parts.filter((p) => !(p.kind === 'text' && p.step === step));
  switch (e.type) {
    case 'text': {
      const last = parts[parts.length - 1];
      if (last?.kind === 'text' && last.step === e.step) parts[parts.length - 1] = { ...last, text: last.text + e.text };
      else parts.push({ kind: 'text', step: e.step, text: e.text });
      return { ...m, parts };
    }
    case 'tool_start':
      return { ...m, parts: [...parts, { kind: 'tool', id: e.id, name: e.name, status: 'running' }] };
    case 'tool_use': {
      const i = parts.findIndex((p) => p.kind === 'tool' && p.id === e.id);
      if (i >= 0) parts[i] = { ...(parts[i] as Extract<Part, { kind: 'tool' }>), input: e.input };
      else parts.push({ kind: 'tool', id: e.id, name: e.name, input: e.input, status: 'running' });
      return { ...m, parts };
    }
    case 'tool_result':
      return { ...m, parts: parts.map((p) => (p.kind === 'tool' && p.id === e.id ? { ...p, status: e.ok ? 'ok' : 'error', provenance: e.provenance } : p)) };
    case 'fallback':
      return { ...m, parts: [...dropStepText(e.step), { kind: 'note', text: t('Continued on {to} after {from} declined.', { to: e.to ?? t('a fallback model'), from: e.from ?? t('the primary model') }) }] };
    case 'retry':
      return { ...m, parts: dropStepText(e.step) };
    case 'refusal':
      return { ...m, parts: dropStepText(e.step), status: 'refused', error: t('Claude declined this request') + (e.category ? ` (${e.category})` : '') + '.' };
    case 'error':
      return { ...m, status: 'error', error: e.message };
    case 'done':
      return { ...m, status: m.status === 'streaming' ? 'done' : m.status, model: e.model, usage: e.usage };
  }
}

function ToolChip({ p }: { p: Extract<Part, { kind: 'tool' }> }) {
  const args = p.input ? Object.entries(p.input).filter(([k]) => k !== 'city').map(([, v]) => String(v)).join(' · ') : '';
  return (
    <span title={p.input ? JSON.stringify(p.input) : p.name} className="inline-flex items-center gap-1 rounded border border-ink-600 bg-ink-800 px-1.5 py-0.5 text-[11px] text-ink-300">
      {p.status === 'running' ? <Loader2 className="size-3 animate-spin text-accent" /> : p.status === 'ok' ? <Check className="size-3 text-src-sensor" /> : <AlertTriangle className="size-3 text-src-sim" />}
      <Wrench className="size-3 opacity-60" />
      {t(TOOL_LABEL[p.name] ?? p.name)}
      {args && <span className="text-ink-400">· {args}</span>}
    </span>
  );
}

function LlmMessage({ m }: { m: Extract<Msg, { engine: 'llm' }> }) {
  const sources = new Map<string, Provenance>();
  for (const p of m.parts) if (p.kind === 'tool' && p.provenance) sources.set(`${p.provenance.source}|${p.provenance.provider}`, p.provenance);
  const tools = m.parts.filter((p): p is Extract<Part, { kind: 'tool' }> => p.kind === 'tool');
  const text = llmText(m);
  return (
    <>
      {tools.length > 0 && <div className="mb-2 flex flex-wrap gap-1">{tools.map((p) => <ToolChip key={p.id} p={p} />)}</div>}
      {m.parts.filter((p) => p.kind === 'note').map((p, i) => <p key={i} className="mb-1 text-[11px] text-src-sim">{(p as { text: string }).text}</p>)}
      {text ? <Markdown text={text} /> : m.status === 'streaming' && <p className="text-ink-400">{t(tools.length ? 'Analysing tool results…' : 'Thinking…')}</p>}
      {m.status === 'streaming' && text && <span className="ml-0.5 inline-block h-3.5 w-1.5 animate-pulse bg-accent align-middle" />}
      {m.error && <p className="mt-2 flex items-center gap-1.5 text-[12px] text-src-sim"><AlertTriangle className="size-3.5" /> {t(m.error)}</p>}
      {(sources.size > 0 || m.status === 'done') && (
        <div className="mt-2 flex flex-wrap items-center gap-1 border-t border-ink-700 pt-2">
          <SourceBadge p={AI_PROVENANCE} compact />
          {[...sources.values()].map((s) => <SourceBadge key={`${s.source}|${s.provider}`} p={s} />)}
          {m.model && m.usage && (
            <span className="ml-auto text-[10px] text-ink-400" title={t('Tokens across all tool rounds (cache reads in brackets)')}>
              {m.model} · {m.usage.input.toLocaleString(locale())} {t('in')} [{m.usage.cacheRead.toLocaleString(locale())}] / {m.usage.output.toLocaleString(locale())} {t('out')}
            </span>
          )}
        </div>
      )}
    </>
  );
}

export function AssistantPage() {
  const data = useCity();
  const aiAvailable = !!data.backend.data?.ai?.enabled;
  const [preferRules, setPreferRules] = useState(false);
  const useAi = aiAvailable && !preferRules;
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [q, setQ] = useState('');
  const abortRef = useRef<AbortController | null>(null);
  const endRef = useRef<HTMLDivElement>(null);
  const busy = msgs.some((m) => m.role === 'assistant' && m.engine === 'llm' && m.status === 'streaming');

  useEffect(() => {
    abortRef.current?.abort();
    setMsgs([{ role: 'assistant', engine: 'intro', text: t("Hello — I'm CityTwin AI. I analyse the data available for {city} and cite where each value comes from. I won't invent measurements.", { city: data.city.name }) }]);
    // Reset the conversation when the city changes.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [data.city.id]);

  useEffect(() => () => abortRef.current?.abort(), []);

  useEffect(() => {
    // Braces matter: newer browsers return a Promise from scrollIntoView.
    endRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [msgs]);

  const askRules = (question: string) => {
    const a = answer(question, data);
    setMsgs((m) => [...m, { role: 'user', text: question }, { role: 'assistant', engine: 'rules', text: a.text, sources: a.sources }]);
  };

  const askAi = async (question: string) => {
    // Plain-text history: questions and the final text of earlier answers.
    const history: ChatTurn[] = [];
    for (const m of msgs) {
      if (m.role === 'user') history.push({ role: 'user', content: m.text });
      else if (m.engine === 'llm' && m.status === 'done' && llmText(m)) history.push({ role: 'assistant', content: llmText(m) });
      else if (m.engine === 'rules') history.push({ role: 'assistant', content: m.text });
    }
    history.push({ role: 'user', content: question });
    while (history.length > 40) history.shift();
    while (history[0]?.role !== 'user') history.shift();

    const ctrl = new AbortController();
    abortRef.current = ctrl;
    setMsgs((m) => [...m, { role: 'user', text: question }, { role: 'assistant', engine: 'llm', parts: [], status: 'streaming' }]);
    const update = (f: (m: Extract<Msg, { engine: 'llm' }>) => Extract<Msg, { engine: 'llm' }>) =>
      setMsgs((all) => {
        const i = all.length - 1;
        const last = all[i];
        if (last?.role !== 'assistant' || last.engine !== 'llm') return all;
        const next = [...all];
        next[i] = f(last);
        return next;
      });
    try {
      await streamChat(data.city.id, history, (e) => update((m) => applyEvent(m, e)), ctrl.signal);
      update((m) => (m.status === 'streaming' ? { ...m, status: 'error', error: t('The connection closed before the answer finished.') } : m));
    } catch (err) {
      const aborted = ctrl.signal.aborted;
      update((m) => ({ ...m, status: aborted ? 'done' : 'error', error: aborted ? t('Stopped.') : (err as Error).message }));
    }
  };

  const ask = (text: string) => {
    const question = text.trim();
    if (!question || busy) return;
    setQ('');
    if (useAi) void askAi(question);
    else askRules(question);
  };

  return (
    <div className="flex h-full flex-col">
      <div className="flex items-center gap-3 border-b border-ink-700 px-4 py-2.5">
        <Bot className="size-5 text-accent" />
        <div className="min-w-0">
          <h1 className="font-semibold">CityTwin AI · {data.city.name}</h1>
          <p className="truncate text-[11px] text-ink-400">
            {useAi
              ? t('Claude ({model}) with read-only tools over PostGIS, live sensors, anomalies, weather and traffic.', { model: data.backend.data?.ai?.model ?? '' })
              : aiAvailable
                ? t('Rule-based engine over the data loaded in this browser.')
                : data.backend.data
                  ? t('Rule-based engine. Set ANTHROPIC_API_KEY on the backend to enable Claude.')
                  : t('Rule-based engine. Start the CityTwin backend with ANTHROPIC_API_KEY to enable Claude.')}
          </p>
        </div>
        <div className="ml-auto flex items-center gap-2">
          {aiAvailable && (
            <div className="flex rounded border border-ink-600 text-[11px]">
              <button onClick={() => setPreferRules(false)} className={`flex items-center gap-1 px-2 py-1 ${useAi ? 'bg-accent/15 text-accent' : 'text-ink-300'}`}><Sparkles className="size-3" /> Claude</button>
              <button onClick={() => setPreferRules(true)} className={`px-2 py-1 ${!useAi ? 'bg-accent/15 text-accent' : 'text-ink-300'}`}>{t('Rules')}</button>
            </div>
          )}
          <SourceBadge p={useAi ? AI_PROVENANCE : ENGINE_PROVENANCE} />
        </div>
      </div>
      <div className="flex-1 overflow-y-auto px-4 py-4">
        <div className="mx-auto flex max-w-3xl flex-col gap-3">
          {msgs.map((m, i) => (
            <div key={i} className={`fade-in flex gap-2.5 ${m.role === 'user' ? 'flex-row-reverse' : ''}`}>
              <div className={`flex size-7 shrink-0 items-center justify-center rounded-full ${m.role === 'user' ? 'bg-ink-700 text-ink-200' : 'bg-accent/15 text-accent'}`}>
                {m.role === 'user' ? <User className="size-3.5" /> : m.engine === 'llm' ? <Sparkles className="size-3.5" /> : <Bot className="size-3.5" />}
              </div>
              <div className={`max-w-[85%] rounded-md border px-3 py-2 ${m.role === 'user' ? 'border-ink-600 bg-ink-800' : 'border-ink-700 bg-ink-850'}`}>
                {m.role === 'user' || m.engine === 'intro' ? (
                  <p className="whitespace-pre-wrap text-ink-100">{m.text}</p>
                ) : m.engine === 'rules' ? (
                  <>
                    <p className="whitespace-pre-wrap text-ink-100">{m.text}</p>
                    {m.sources.length > 0 && (
                      <div className="mt-2 flex flex-wrap gap-1 border-t border-ink-700 pt-2">
                        {m.sources.map((s) => <SourceBadge key={s.provider} p={s} />)}
                      </div>
                    )}
                  </>
                ) : (
                  <LlmMessage m={m} />
                )}
              </div>
            </div>
          ))}
          <div ref={endRef} />
        </div>
      </div>
      <div className="border-t border-ink-700 px-4 py-3">
        <div className="mx-auto max-w-3xl">
          <div className="mb-2 flex flex-wrap gap-1.5">
            {(useAi ? AI_QUESTIONS : SUGGESTED_QUESTIONS).map((s) => (
              <button key={s} onClick={() => ask(t(s))} disabled={busy} className="rounded-full border border-ink-600 px-2.5 py-1 text-xs text-ink-300 hover:border-accent hover:text-accent disabled:opacity-40">
                {t(s)}
              </button>
            ))}
          </div>
          <form onSubmit={(e) => { e.preventDefault(); ask(q); }} className="flex gap-2">
            <input
              value={q}
              onChange={(e) => setQ(e.target.value)}
              maxLength={4000}
              placeholder={t(useAi ? 'Ask anything about this city’s data…' : 'Ask about air quality, traffic, energy, alerts…')}
              className="h-9 flex-1 rounded border border-ink-600 bg-ink-800 px-3 text-ink-100 outline-none placeholder:text-ink-400 focus:border-accent"
            />
            {busy ? (
              <button type="button" onClick={() => abortRef.current?.abort()} className="flex h-9 items-center gap-1.5 rounded border border-ink-500 px-3 text-ink-200 hover:border-accent">
                <Square className="size-3.5" /> {t('Stop')}
              </button>
            ) : (
              <button type="submit" disabled={!q.trim()} className="flex h-9 items-center gap-1.5 rounded bg-accent px-3 font-medium text-ink-950 disabled:opacity-40">
                <Send className="size-3.5" /> {t('Ask')}
              </button>
            )}
          </form>
        </div>
      </div>
    </div>
  );
}
